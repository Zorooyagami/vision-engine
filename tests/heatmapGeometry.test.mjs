import assert from 'node:assert/strict';
import { projectClick, clusterClicks } from '../admin/src/components/tools/heatmaps/heatmapGeometry.mjs';
const capture = { key:'layout-v1-abcd', width:1440, height:2400 };
const event = (x,y, key=capture.key, name='click') => ({ event:name, properties:{ coordinateSpace:'document-px-v4',layoutKey:key,xPx:x,yPx:y,targetId:'fake-button'} });
assert.deepEqual(projectClick(event(720,1200),capture,720,1200),{x:360,y:600});
assert.deepEqual(projectClick(event(0,0),capture,1440,2400),{x:0,y:0});
assert.equal(projectClick(event(1400,100,'other-layout'),capture,1440,2400),null);
assert.equal(projectClick(event(1441,100),capture,1440,2400),null);
assert.equal(projectClick({properties:{xPx:400,yPx:400,layoutKey:capture.key,coordinateSpace:'document-px-v3'}},capture,1440,2400),null);
assert.equal(projectClick(event(100,100,'layout-v1-abcd'),{...capture,width:0},1440,2400),null);
const clicks = Array.from({length:40},()=>event(415,555));
const clustered = clusterClicks(clicks,capture,1440,2400);
assert.equal(clustered[0].count,40);
assert.ok(Math.abs(clustered[0].x - 415) < 0.001);
assert.ok(Math.abs(clustered[0].y - 555) < 0.001);
const spaced = clusterClicks([event(100,100),event(500,500)],capture,1440,2400);
assert.equal(spaced.length,2);
assert.equal(spaced[0].x,100);
console.log('8 heatmap geometry regression checks passed');
